#!/usr/bin/env node
import fs from "fs";
import path from "path";
import crypto from "crypto";
import sharp from "sharp";
import { fileURLToPath } from "url";
import {
  collectContentImagePaths,
  resolvePublicImage,
} from "./collect-content-image-paths.mjs";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT_DIR = path.join(root, "public", "_next-static-images");
const MANIFEST_TS = path.join(root, "lib", "generated", "image-variants.ts");
const WIDTHS = [640, 1080, 1920];
const WEBP_QUALITY = 82;

function cacheKey(absPath) {
  const st = fs.statSync(absPath);
  return crypto
    .createHash("sha1")
    .update(`${absPath}:${st.mtimeMs}:${st.size}`)
    .digest("hex")
    .slice(0, 12);
}

function publicUrlFromFile(outFile) {
  const rel = path.relative(path.join(root, "public"), outFile);
  return `/${rel.split(path.sep).join("/")}`;
}

async function main() {
  const paths = collectContentImagePaths();
  const manifest = {};

  fs.mkdirSync(OUTPUT_DIR, { recursive: true });
  fs.mkdirSync(path.dirname(MANIFEST_TS), { recursive: true });

  for (const src of paths) {
    if (/\.svg$/i.test(src)) continue;

    const abs = resolvePublicImage(src);
    if (!fs.existsSync(abs)) {
      console.error(`Skip missing (should have been caught by verify): ${src}`);
      continue;
    }

    const key = cacheKey(abs);
    const outDir = path.join(OUTPUT_DIR, key);
    fs.mkdirSync(outDir, { recursive: true });

    const meta = await sharp(abs).metadata();
    const intrinsicWidth = meta.width ?? 1920;
    const intrinsicHeight = meta.height ?? 0;
    const sources = {};

    for (const w of WIDTHS) {
      const targetWidth = Math.min(w, intrinsicWidth);
      const outName = `w${targetWidth}.webp`;
      const outFile = path.join(outDir, outName);

      if (!fs.existsSync(outFile)) {
        await sharp(abs)
          .resize({ width: targetWidth, withoutEnlargement: true })
          .webp({ quality: WEBP_QUALITY })
          .toFile(outFile);
      }

      sources[String(targetWidth)] = publicUrlFromFile(outFile);
    }

    manifest[src] = {
      width: intrinsicWidth,
      height: intrinsicHeight,
      sources,
    };
  }

  const ts = `/* eslint-disable */\n/** Generated by scripts/generate-responsive-images.mjs — do not edit */\nexport const imageVariants = ${JSON.stringify(manifest, null, 2)} as const;\nexport type ImageVariantKey = keyof typeof imageVariants;\n`;
  fs.writeFileSync(MANIFEST_TS, ts);
  console.log(
    `Generated ${Object.keys(manifest).length} image variant set(s) → lib/generated/image-variants.ts`
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});